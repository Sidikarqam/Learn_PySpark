"""Menggunakan PySpark"""

def read_big_table_pyspark(filename: str):
  start_time = time.time()

  df = spark \
      .read \
      .option('header', 'true')\
      .csv(filename)

  end_time = time.time()

  elapsed_time = end_time - start_time

  return elapsed_time, df

elapsed_time, df_pyspark = read_big_table_pyspark(filename = "flights_big_data.csv")
