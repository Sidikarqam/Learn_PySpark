"""Menggunakan Multiple Filter"""

# Multiple Filter using PySpark Base
filtered_df = selected_df_flights.filter((selected_df_flights['MONTH'] > 5) & (selected_df_flights['ORIGIN_AIRPORT'] == 'LAX'))

